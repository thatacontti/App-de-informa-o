export function normalizeCategoria(s) {
  return String(s ?? '')
    .replace(/\s+/g, ' ')
    .trim()
    .toUpperCase();
}

const _MAP = new Map(
  Object.entries(CATEGORIA_TO_GRUPO_RAW).map(([k, v]) => [normalizeCategoria(k), v]),
);

// Retorna o Grupo canônico se a Categoria estiver mapeada; senão devolve
// o input original (assim valores não previstos não são silenciosamente
// descartados — aparecem nos relatórios pra serem incluídos na tabela).
export function mapCategoriaToGrupo(categoria) {
  if (categoria == null) return categoria;
  const found = _MAP.get(normalizeCategoria(categoria));
  return found ?? categoria;
}

export function isMapped(categoria) {
  return _MAP.has(normalizeCategoria(categoria));
}
